export type CareLoopStage = 
  | 'detect'        // 1. Warning detected from vitals/symptoms
  | 'explain'       // 2. MEOWS rationale & triggers explained
  | 'prioritize'    // 3. Clinical triage & doctor escalation
  | 'coordinate'    // 4. Facility referral & transport coordination
  | 'follow_through'; // 5. Closed-loop follow-up & documented outcome

export type Severity = 'critical' | 'warning' | 'stable' | 'info';

