import React, { useState, useEffect } from 'react';
import { 
  CheckSquare, 
  Clock, 
  AlertTriangle, 
  CheckCircle2, 
  UserCheck, 
  Calendar, 
  Plus, 
  ShieldAlert, 
  VolumeX, 
  Home,
  Check
} from 'lucide-react';
import { localDb } from '../db/localDb';
import { syncService } from '../db/syncService';
import { useAuth } from '../context/AuthContext';
import { useNetwork } from '../context/NetworkContext';
import confetti from 'canvas-confetti';
import type { Task, Patient } from '../types';

interface TasksViewProps {
  onSelectPatient: (patientId: string) => void;
  onNavigate: (view: any) => void;
}

export const TasksView: React.FC<TasksViewProps> = ({
  onSelectPatient,
  onNavigate
}) => {
  const { profile } = useAuth();
  const { isOnline } = useNetwork();

  const [tasks, setTasks] = useState<Task[]>([]);
  const [patients, setPatients] = useState<Record<string, Patient>>({});
  const [filter, setFilter] = useState<'all' | 'open' | 'overdue' | 'completed' | 'silent'>('all');

  // New task form state
  const [isAddingTask, setIsAddingTask] = useState<boolean>(false);
  const [newTaskPatientId, setNewTaskPatientId] = useState<string>('PT-101');
  const [newTaskTitle, setNewTaskTitle] = useState<string>('Postnatal Day 7 Follow-Up Check');
  const [newTaskDescription, setNewTaskDescription] = useState<string>('Home visit to evaluate maternal blood pressure and newborn feeding.');
  const [newTaskAssignee, setNewTaskAssignee] = useState<string>('Meena (ANM)');

  const loadTasks = async () => {
    try {
      const taskList = await localDb.tasks.reverse().sortBy('dueDate');
      setTasks(taskList);

      const ptList = await localDb.patients.toArray();
      const ptMap: Record<string, Patient> = {};
      ptList.forEach(p => { ptMap[p.id] = p; });
      setPatients(ptMap);
    } catch (e) {
      console.error(e);
    }
  };

  useEffect(() => {
    loadTasks();
  }, []);

  const handleMarkTaskComplete = async (task: Task) => {
    const timestamp = new Date().toISOString();
    const updatedTask: Task = {
      ...task,
      status: 'completed',
      completedAt: timestamp,
      completedBy: profile.name,
      completionNote: 'Completed successfully by health worker with normal findings.'
    };

    await localDb.tasks.put(updatedTask);

    // Check if patient can now close their Care Loop
    const patient = patients[task.patientId];
    if (patient) {
      await localDb.patients.update(patient.id, {
        isClosed: true,
        closedAt: timestamp,
        closedOutcome: patient.closedOutcome || 'Home follow-up verified. Mother and child stable.',
        outstandingTask: undefined,
        outstandingOwner: undefined
      });

      try {
        confetti({ particleCount: 70, spread: 60, origin: { y: 0.7 } });
      } catch (e) {}
    }

    // Sync queue
    await syncService.enqueueAction({
      user: profile.name,
      device: `${profile.title} Device`,
      action: `Completed Task: "${task.title}" for ${task.patientName}`,
      entityType: 'task',
      payload: updatedTask
    });

    // Audit Log
    await localDb.auditLogs.add({
      id: `AUD-${Date.now()}`,
      timestamp,
      actor: profile.name,
      role: profile.title,
      facility: profile.facility,
      action: 'Completed Follow-up Task & Care Loop Closed',
      patientId: task.patientId,
      patientName: task.patientName,
      details: `Task "${task.title}" verified complete. Longitudinal loop marked CLOSED with documented outcome.`,
      online: isOnline,
      device: `${profile.title} Device`
    });

    await loadTasks();
  };

  const handleCreateTask = async (e: React.FormEvent) => {
    e.preventDefault();
    const patient = patients[newTaskPatientId];
    if (!patient) return;

    const newTask: Task = {
      id: `TSK-${Date.now()}`,
      patientId: patient.id,
      patientName: patient.name,
      title: newTaskTitle,
      description: newTaskDescription,
      assignedTo: newTaskAssignee,
      assignedRole: 'Nurse/ANM',
      facility: profile.facility,
      dueDate: new Date(Date.now() + 48 * 60 * 60 * 1000).toISOString(),
      status: 'open',
      isAutoGenerated: false,
      isSilentPatientFlag: false
    };

    await localDb.tasks.add(newTask);

    await syncService.enqueueAction({
      user: profile.name,
      device: `${profile.title} Device`,
      action: `Created Follow-up Task for ${patient.name}`,
      entityType: 'task',
      payload: newTask
    });

    setIsAddingTask(false);
    await loadTasks();
  };

  const filteredTasks = tasks.filter(t => {
    if (filter === 'open') return t.status === 'open';
    if (filter === 'overdue') return t.status === 'overdue';
    if (filter === 'completed') return t.status === 'completed';
    if (filter === 'silent') return t.isSilentPatientFlag;
    return true;
  });

  return (
    <div className="max-w-6xl mx-auto p-3 sm:p-6 space-y-5 animate-fadeIn">
      {/* Header */}
      <div className="card-base p-4 sm:p-5 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-teal-500/10 text-[var(--primary)] flex items-center justify-center font-bold">
            <CheckSquare className="w-5 h-5" />
          </div>
          <div>
            <h2 className="text-lg sm:text-xl font-black text-[var(--text-main)]">
              Follow-Up Tasks &amp; Closed-Loop Tracker
            </h2>
            <p className="text-xs text-[var(--text-muted)]">
              A Care Loop is never closed until a documented outcome and home follow-up exist.
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={() => setIsAddingTask(true)}
            className="btn-primary !py-2 !px-3 text-xs font-bold"
          >
            <Plus className="w-4 h-4" />
            <span>+ Add Custom Task</span>
          </button>
        </div>
      </div>

      {/* Filter Tabs */}
      <div className="flex items-center gap-1.5 overflow-x-auto pb-1">
        {[
          { id: 'all', label: `All Tasks (${tasks.length})` },
          { id: 'open', label: `Open (${tasks.filter(t => t.status === 'open').length})` },
          { id: 'overdue', label: `Overdue (${tasks.filter(t => t.status === 'overdue').length})` },
          { id: 'silent', label: `Silent Patients (${tasks.filter(t => t.isSilentPatientFlag).length})` },
          { id: 'completed', label: `Completed (${tasks.filter(t => t.status === 'completed').length})` }
        ].map(tab => (
          <button
            key={tab.id}
            type="button"
            onClick={() => setFilter(tab.id as any)}
            className={`px-3 py-1.5 rounded-xl text-xs font-bold transition-all whitespace-nowrap cursor-pointer ${
              filter === tab.id
                ? 'bg-[var(--primary)] text-white shadow-xs'
                : 'card-base text-[var(--text-muted)] hover:text-[var(--text-main)]'
            }`}
          >
            {tab.label}
          </button>
        ))}
      </div>

      {/* Add Task Form (Inline accordion) */}
      {isAddingTask && (
        <form onSubmit={handleCreateTask} className="card-base p-4 sm:p-5 space-y-3 animate-slideDown">
          <h3 className="text-sm font-extrabold text-[var(--text-main)]">
            Create Follow-Up Task
          </h3>
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
            <div>
              <label htmlFor="select-patient-task" className="block font-bold text-[var(--text-muted)] mb-1">
                Select Patient
              </label>
              <select
                id="select-patient-task"
                value={newTaskPatientId}
                onChange={(e) => setNewTaskPatientId(e.target.value)}
                className="w-full p-2.5 rounded-xl border border-[var(--border-main)] bg-[var(--bg-main)] text-xs text-[var(--text-main)] outline-none"
              >
                {(Object.values(patients) as Patient[]).map(p => (
                  <option key={p.id} value={p.id}>
                    {p.name} ({p.gestationWeeks}w, {p.village})
                  </option>
                ))}
              </select>
            </div>
            <div>
              <label htmlFor="task-assignee-select" className="block font-bold text-[var(--text-muted)] mb-1">
                Assigned Staff Member
              </label>
              <input
                id="task-assignee-select"
                type="text"
                value={newTaskAssignee}
                onChange={(e) => setNewTaskAssignee(e.target.value)}
                className="w-full p-2.5 rounded-xl border border-[var(--border-main)] bg-[var(--bg-main)] text-xs text-[var(--text-main)] outline-none"
                required
              />
            </div>
          </div>

          <div className="text-xs">
            <label htmlFor="new-task-title-input" className="block font-bold text-[var(--text-muted)] mb-1">
              Task Title
            </label>
            <input
              id="new-task-title-input"
              type="text"
              value={newTaskTitle}
              onChange={(e) => setNewTaskTitle(e.target.value)}
              className="w-full p-2.5 rounded-xl border border-[var(--border-main)] bg-[var(--bg-main)] text-xs text-[var(--text-main)] outline-none"
              required
            />
          </div>

          <div className="text-xs">
            <label htmlFor="new-task-desc-textarea" className="block font-bold text-[var(--text-muted)] mb-1">
              Task Description &amp; Verification Protocol
            </label>
            <textarea
              id="new-task-desc-textarea"
              rows={2}
              value={newTaskDescription}
              onChange={(e) => setNewTaskDescription(e.target.value)}
              className="w-full p-2.5 rounded-xl border border-[var(--border-main)] bg-[var(--bg-main)] text-xs text-[var(--text-main)] outline-none"
              required
            />
          </div>

          <div className="flex items-center justify-end gap-2 pt-2">
            <button
              type="button"
              onClick={() => setIsAddingTask(false)}
              className="btn-secondary text-xs"
            >
              Cancel
            </button>
            <button
              type="submit"
              className="btn-primary text-xs font-bold"
            >
              Save &amp; Assign Task
            </button>
          </div>
        </form>
      )}

      {/* Task List Cards */}
      <div className="space-y-3">
        {filteredTasks.length === 0 ? (
          <div className="card-base p-12 text-center text-xs text-[var(--text-muted)]">
            No tasks in "{filter}" view.
          </div>
        ) : (
          filteredTasks.map((task) => {
            const isOverdue = task.status === 'overdue';
            const isDone = task.status === 'completed';

            return (
              <div
                key={task.id}
                className={`card-base p-4 sm:p-5 transition-all flex flex-col md:flex-row md:items-center justify-between gap-3 ${
                  isOverdue
                    ? 'border-red-500 bg-red-500/5'
                    : task.isSilentPatientFlag
                    ? 'border-amber-500 bg-amber-500/5'
                    : isDone
                    ? 'opacity-85'
                    : ''
                }`}
              >
                {/* Left */}
                <div className="space-y-1.5 flex-1">
                  <div className="flex items-center gap-2.5 flex-wrap">
                    <button
                      type="button"
                      onClick={() => {
                        onSelectPatient(task.patientId);
                        onNavigate('patient-detail');
                      }}
                      className="font-black text-sm sm:text-base text-[var(--text-main)] hover:text-[var(--primary)] cursor-pointer"
                    >
                      {task.patientName}
                    </button>

                    <span
                      className={`text-[10px] font-bold px-2 py-0.5 rounded-full uppercase ${
                        isOverdue
                          ? 'bg-red-500 text-white'
                          : isDone
                          ? 'badge-stable'
                          : 'badge-warning'
                      }`}
                    >
                      {task.status}
                    </span>

                    {task.isSilentPatientFlag && (
                      <span className="badge-critical text-[10px] font-bold px-2 py-0.5 rounded-full flex items-center gap-1">
                        <VolumeX className="w-3 h-3" /> Silent Patient Tracing
                      </span>
                    )}

                    {task.isAutoGenerated && (
                      <span className="text-[10px] font-mono font-semibold px-2 py-0.5 rounded bg-black/5 dark:bg-white/5 text-[var(--text-muted)]">
                        Auto-Generated from Referral Outcome
                      </span>
                    )}
                  </div>

                  <h3 className="font-extrabold text-sm text-[var(--text-main)]">
                    {task.title}
                  </h3>

                  <p className="text-xs text-[var(--text-muted)] leading-relaxed">
                    {task.description}
                  </p>

                  <div className="text-[11px] text-[var(--text-muted)] pt-1 flex flex-wrap items-center gap-3">
                    <span>Assigned to: <strong>{task.assignedTo}</strong></span>
                    <span>•</span>
                    <span className={`font-semibold ${isOverdue ? 'text-red-500 font-bold' : ''}`}>
                      Due: {new Date(task.dueDate).toLocaleDateString()}
                    </span>
                    {task.completedAt && (
                      <>
                        <span>•</span>
                        <span className="text-emerald-600 dark:text-emerald-400 font-bold">
                          Completed: {new Date(task.completedAt).toLocaleTimeString()}
                        </span>
                      </>
                    )}
                  </div>

                  {task.completionNote && (
                    <div className="p-2 rounded-lg bg-emerald-500/10 text-emerald-700 dark:text-emerald-300 text-xs font-medium mt-1">
                      {task.completionNote}
                    </div>
                  )}
                </div>

                {/* Right: Mark Complete Button */}
                <div className="flex items-center gap-2 shrink-0 pt-2 md:pt-0 border-t md:border-t-0 border-[var(--border-main)]">
                  {!isDone ? (
                    <button
                      type="button"
                      onClick={() => handleMarkTaskComplete(task)}
                      className="btn-primary !py-2 !px-3 text-xs font-bold flex items-center gap-1.5 !bg-emerald-600 hover:!bg-emerald-700 shadow-md"
                    >
                      <Check className="w-4 h-4" />
                      <span>Complete &amp; Close Care Loop</span>
                    </button>
                  ) : (
                    <span className="badge-stable text-xs font-bold px-3 py-1.5 rounded-xl flex items-center gap-1">
                      <CheckCircle2 className="w-4 h-4" /> Loop Closed
                    </span>
                  )}
                </div>
              </div>
            );
          })
        )}
      </div>
    </div>
  );
};
